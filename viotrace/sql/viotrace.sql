-- =====================================================================
-- VioTrace: DMP Traffic Management System
-- Schema (3NF), constraints, triggers, procedures, view, seed data
-- Import with phpMyAdmin (Import tab) or:  mysql -u root < viotrace.sql
-- WARNING: drops and recreates the `viotrace` database.
-- =====================================================================
DROP DATABASE IF EXISTS viotrace;
CREATE DATABASE viotrace CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE viotrace;

-- ---------------------------------------------------------------------
-- 1. TABLES
-- ---------------------------------------------------------------------
CREATE TABLE drivers (
  driver_id      INT AUTO_INCREMENT PRIMARY KEY,
  license_no     VARCHAR(10)  NOT NULL UNIQUE,         -- DL + 8 digits, e.g. DL00000001
  full_name      VARCHAR(100) NOT NULL,
  phone          VARCHAR(20),
  address        VARCHAR(255),
  date_of_birth  DATE NOT NULL,
  license_expiry DATE NOT NULL,
  created_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_license_format CHECK (license_no REGEXP '^DL[0-9]{8}$'),
  CONSTRAINT chk_license_dates CHECK (license_expiry > date_of_birth)
) ENGINE=InnoDB;

CREATE TABLE users (
  user_id         INT AUTO_INCREMENT PRIMARY KEY,
  username        VARCHAR(50)  NOT NULL UNIQUE,         -- admin: adminDC/adminN, officer: DMP ID, citizen: mobile number
  password_hash   VARCHAR(255) NOT NULL,
  pin_hash        VARCHAR(255) NULL,                    -- second factor, admins only
  full_name       VARCHAR(100) NOT NULL,
  email           VARCHAR(120) NULL UNIQUE,
  role            ENUM('admin','officer','citizen') NOT NULL,
  admin_type      ENUM('main','staff') NULL,            -- admins only; main = adminDC
  approval_status ENUM('Pending','Approved','Rejected') NOT NULL DEFAULT 'Approved',
  created_by      INT NULL,
  approved_by     INT NULL,
  nid             VARCHAR(17) NULL UNIQUE,              -- citizens only: 10 or 17 digits
  driver_id       INT NULL UNIQUE,                      -- citizens only
  is_active       TINYINT(1) NOT NULL DEFAULT 1,
  created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_users_driver   FOREIGN KEY (driver_id)   REFERENCES drivers(driver_id),
  CONSTRAINT fk_users_creator  FOREIGN KEY (created_by)  REFERENCES users(user_id),
  CONSTRAINT fk_users_approver FOREIGN KEY (approved_by) REFERENCES users(user_id),
  CONSTRAINT chk_admin_pin CHECK (role <> 'admin' OR (pin_hash IS NOT NULL AND admin_type IS NOT NULL)),
  CONSTRAINT chk_nid_format CHECK (nid IS NULL OR nid REGEXP '^([0-9]{10}|[0-9]{17})$')
) ENGINE=InnoDB;

CREATE TABLE officers (
  officer_id   INT AUTO_INCREMENT PRIMARY KEY,
  user_id      INT NOT NULL UNIQUE,
  badge_no     VARCHAR(20) NOT NULL UNIQUE,
  officer_rank VARCHAR(40) NOT NULL,
  station      VARCHAR(80) NOT NULL,
  CONSTRAINT fk_officers_user FOREIGN KEY (user_id) REFERENCES users(user_id)
) ENGINE=InnoDB;

CREATE TABLE vehicles (
  vehicle_id        INT AUTO_INCREMENT PRIMARY KEY,
  reg_no            VARCHAR(40) NOT NULL UNIQUE,        -- e.g. DHAKA METRO-HA-11-2345
  vehicle_type      ENUM('Car','Motorcycle','Microbus','Bus','Truck','CNG','Other') NOT NULL,
  make              VARCHAR(50) NOT NULL,
  model             VARCHAR(50) NOT NULL,
  manufacture_year  SMALLINT NOT NULL,
  CONSTRAINT chk_vehicle_year CHECK (manufacture_year BETWEEN 1950 AND 2100),
  CONSTRAINT chk_reg_format CHECK (reg_no REGEXP '^[A-Z][A-Z ]+-[A-Z]{1,3}-[0-9]{2}-[0-9]{4}$')
) ENGINE=InnoDB;

-- Many-to-many between vehicles and drivers over time (ownership history)
CREATE TABLE vehicle_ownership (
  ownership_id INT AUTO_INCREMENT PRIMARY KEY,
  vehicle_id   INT NOT NULL,
  driver_id    INT NOT NULL,
  owned_from   DATE NOT NULL,
  owned_to     DATE NULL,                    -- NULL = current owner
  CONSTRAINT fk_own_vehicle FOREIGN KEY (vehicle_id) REFERENCES vehicles(vehicle_id),
  CONSTRAINT fk_own_driver  FOREIGN KEY (driver_id)  REFERENCES drivers(driver_id),
  CONSTRAINT chk_own_dates  CHECK (owned_to IS NULL OR owned_to >= owned_from),
  INDEX idx_own_vehicle (vehicle_id, owned_to),
  INDEX idx_own_driver (driver_id, owned_to)
) ENGINE=InnoDB;

CREATE TABLE violation_types (
  type_id     INT AUTO_INCREMENT PRIMARY KEY,
  code        VARCHAR(10)  NOT NULL UNIQUE,
  name        VARCHAR(80)  NOT NULL,
  description VARCHAR(255),
  base_fine   DECIMAL(10,2) NOT NULL,
  is_active   TINYINT(1) NOT NULL DEFAULT 1,
  CONSTRAINT chk_base_fine CHECK (base_fine > 0)
) ENGINE=InnoDB;

CREATE TABLE violations (
  violation_id           INT AUTO_INCREMENT PRIMARY KEY,
  case_id                VARCHAR(12) NOT NULL DEFAULT '' UNIQUE,   -- VT-XXXXXXXX, generated by trigger
  vehicle_id             INT NOT NULL,
  driver_id              INT NOT NULL,
  officer_id             INT NOT NULL,
  type_id                INT NOT NULL,
  location               VARCHAR(150) NOT NULL,
  area                   VARCHAR(80)  NOT NULL,
  violation_datetime     DATETIME NOT NULL,
  evidence_photo_ref     VARCHAR(255) NULL,
  evidence_speed_reading SMALLINT UNSIGNED NULL,
  officer_notes          TEXT NULL,
  created_at             TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_vio_vehicle FOREIGN KEY (vehicle_id) REFERENCES vehicles(vehicle_id),
  CONSTRAINT fk_vio_driver  FOREIGN KEY (driver_id)  REFERENCES drivers(driver_id),
  CONSTRAINT fk_vio_officer FOREIGN KEY (officer_id) REFERENCES officers(officer_id),
  CONSTRAINT fk_vio_type    FOREIGN KEY (type_id)    REFERENCES violation_types(type_id),
  INDEX idx_vio_driver (driver_id, violation_datetime),
  INDEX idx_vio_vehicle (vehicle_id),
  INDEX idx_vio_when (violation_datetime)
) ENGINE=InnoDB;

-- One fine per violation. amount/surcharge are a legal snapshot at issue time.
-- Pending = the driver has paid and an administrator has not approved it yet.
CREATE TABLE fines (
  fine_id      INT AUTO_INCREMENT PRIMARY KEY,
  violation_id INT NOT NULL UNIQUE,
  amount       DECIMAL(10,2) NOT NULL,
  surcharge    DECIMAL(10,2) NOT NULL DEFAULT 0,
  total_amount DECIMAL(10,2) GENERATED ALWAYS AS (amount + surcharge) VIRTUAL,
  status       ENUM('Unpaid','Pending','Paid','Overdue','Waived','Refunded') NOT NULL DEFAULT 'Unpaid',
  due_date     DATE NOT NULL,
  paid_at      DATETIME NULL,
  CONSTRAINT fk_fine_violation FOREIGN KEY (violation_id) REFERENCES violations(violation_id),
  CONSTRAINT chk_fine_amount CHECK (amount > 0),
  CONSTRAINT chk_fine_surcharge CHECK (surcharge >= 0),
  INDEX idx_fine_status_due (status, due_date)
) ENGINE=InnoDB;

CREATE TABLE payments (
  payment_id   INT AUTO_INCREMENT PRIMARY KEY,
  fine_id      INT NOT NULL,
  user_id      INT NOT NULL,                  -- payer
  amount       DECIMAL(10,2) NOT NULL,
  method       ENUM('bKash','Nagad','Card','Cash') NOT NULL,
  reference_no VARCHAR(40) NOT NULL UNIQUE,
  status       ENUM('Pending','Approved','Rejected','Failed') NOT NULL,
  note         VARCHAR(255) NULL,
  paid_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  reviewed_by  INT NULL,                      -- administrator who approved/rejected
  reviewed_at  DATETIME NULL,
  review_note  VARCHAR(255) NULL,
  CONSTRAINT fk_pay_fine FOREIGN KEY (fine_id) REFERENCES fines(fine_id),
  CONSTRAINT fk_pay_user FOREIGN KEY (user_id) REFERENCES users(user_id),
  CONSTRAINT fk_pay_reviewer FOREIGN KEY (reviewed_by) REFERENCES users(user_id),
  CONSTRAINT chk_pay_amount CHECK (amount > 0),
  INDEX idx_pay_fine (fine_id),
  INDEX idx_pay_status (status)
) ENGINE=InnoDB;

CREATE TABLE appeals (
  appeal_id     INT AUTO_INCREMENT PRIMARY KEY,
  violation_id  INT NOT NULL UNIQUE,
  driver_id     INT NOT NULL,
  statement     TEXT NOT NULL,
  status        ENUM('Pending','Approved','Rejected') NOT NULL DEFAULT 'Pending',
  admin_id      INT NULL,
  admin_remarks VARCHAR(500) NULL,
  submitted_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  resolved_at   DATETIME NULL,
  CONSTRAINT fk_app_violation FOREIGN KEY (violation_id) REFERENCES violations(violation_id),
  CONSTRAINT fk_app_driver FOREIGN KEY (driver_id) REFERENCES drivers(driver_id),
  CONSTRAINT fk_app_admin  FOREIGN KEY (admin_id)  REFERENCES users(user_id)
) ENGINE=InnoDB;

-- Append-only audit trail (no FKs on purpose: it must outlive everything)
CREATE TABLE audit_log (
  audit_id    BIGINT AUTO_INCREMENT PRIMARY KEY,
  table_name  VARCHAR(30) NOT NULL,
  record_id   INT NOT NULL,
  action      ENUM('INSERT','STATUS_CHANGE') NOT NULL,
  driver_id   INT NULL,
  vehicle_id  INT NULL,
  old_value   VARCHAR(500) NULL,
  new_value   VARCHAR(500) NULL,
  acting_user INT NULL,                      -- NULL = system / self-registration
  created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_audit_driver (driver_id),
  INDEX idx_audit_vehicle (vehicle_id),
  INDEX idx_audit_record (table_name, record_id)
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- 2. TRIGGERS
--    The web app runs  SET @current_user_id = <id>  on every connection,
--    so audit rows and permission checks know who is acting.
-- ---------------------------------------------------------------------
DELIMITER $$

-- ===== users: ID formats, age, admin approval rules
CREATE TRIGGER trg_users_bi BEFORE INSERT ON users FOR EACH ROW
BEGIN
  DECLARE v_age INT;
  IF NEW.role = 'officer' AND NEW.username NOT REGEXP '^DMP[0-9]{11}$' THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Officer ID must look like DMP04325200001.';
  END IF;
  IF NEW.role = 'citizen' THEN
    IF NEW.username NOT REGEXP '^01[3-9][0-9]{8}$' THEN
      SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'A citizen username must be a mobile number such as 01711000001.';
    END IF;
    IF NEW.nid IS NULL OR NEW.nid NOT REGEXP '^([0-9]{10}|[0-9]{17})$' THEN
      SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'NID must be 10 or 17 digits.';
    END IF;
    IF NEW.driver_id IS NULL THEN
      SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'A citizen account must be linked to a driver record.';
    END IF;
    SELECT TIMESTAMPDIFF(YEAR, date_of_birth, CURDATE()) INTO v_age FROM drivers WHERE driver_id = NEW.driver_id;
    IF v_age IS NULL OR v_age < 18 THEN
      SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'You must be at least 18 years old to register.';
    END IF;
  END IF;
  IF NEW.role = 'admin' THEN
    IF NEW.pin_hash IS NULL THEN
      SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Admin accounts need a PIN.';
    END IF;
    -- an admin ID created by anyone except the main admin always starts as Pending
    IF @current_user_id IS NOT NULL AND NOT EXISTS
       (SELECT 1 FROM users WHERE user_id = @current_user_id AND admin_type = 'main' AND approval_status = 'Approved') THEN
      SET NEW.approval_status = 'Pending';
    END IF;
  END IF;
END$$

CREATE TRIGGER trg_users_ai AFTER INSERT ON users FOR EACH ROW
BEGIN
  INSERT INTO audit_log (table_name, record_id, action, driver_id, new_value, acting_user)
  VALUES ('users', NEW.user_id, 'INSERT', NEW.driver_id,
          CONCAT('role=', NEW.role, '; username=', NEW.username, '; approval=', NEW.approval_status), @current_user_id);
END$$

CREATE TRIGGER trg_users_bu BEFORE UPDATE ON users FOR EACH ROW
BEGIN
  IF NEW.role <> OLD.role OR NOT (NEW.admin_type <=> OLD.admin_type) THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Role and admin type cannot be changed.';
  END IF;
  IF NEW.approval_status <> OLD.approval_status THEN
    IF OLD.approval_status <> 'Pending' THEN
      SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Only a pending admin ID can be approved or rejected.';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM users WHERE user_id = @current_user_id AND admin_type = 'main' AND approval_status = 'Approved') THEN
      SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Only the main admin (adminDC) can approve or reject admin IDs.';
    END IF;
  END IF;
END$$

CREATE TRIGGER trg_users_au AFTER UPDATE ON users FOR EACH ROW
BEGIN
  IF NEW.approval_status <> OLD.approval_status THEN
    INSERT INTO audit_log (table_name, record_id, action, old_value, new_value, acting_user)
    VALUES ('users', NEW.user_id, 'STATUS_CHANGE', CONCAT('approval=', OLD.approval_status),
            CONCAT('username=', NEW.username, '; approval=', NEW.approval_status), @current_user_id);
  END IF;
END$$

CREATE TRIGGER trg_users_bd BEFORE DELETE ON users FOR EACH ROW
BEGIN
  SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'User accounts cannot be deleted.';
END$$

-- ===== violations: unique case ID, validate, auto-fine with surcharge, audit
CREATE TRIGGER trg_violations_bi BEFORE INSERT ON violations FOR EACH ROW
BEGIN
  DECLARE v_case VARCHAR(12);
  IF NEW.violation_datetime > NOW() THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Violation time cannot be in the future.';
  END IF;
  IF NEW.case_id IS NULL OR NEW.case_id = '' THEN
    SET v_case = CONCAT('VT-', UPPER(SUBSTRING(MD5(CONCAT(RAND(), UUID())), 1, 8)));
    WHILE EXISTS (SELECT 1 FROM violations WHERE case_id = v_case) DO
      SET v_case = CONCAT('VT-', UPPER(SUBSTRING(MD5(CONCAT(RAND(), UUID())), 1, 8)));
    END WHILE;
    SET NEW.case_id = v_case;
  END IF;
END$$

CREATE TRIGGER trg_violations_ai AFTER INSERT ON violations FOR EACH ROW
BEGIN
  DECLARE v_base  DECIMAL(10,2);
  DECLARE v_prior INT;
  DECLARE v_rate  DECIMAL(4,2) DEFAULT 0;

  SELECT base_fine INTO v_base FROM violation_types WHERE type_id = NEW.type_id;

  -- repeat offender = earlier violations by the same driver in the last 365 days
  SELECT COUNT(*) INTO v_prior FROM violations
   WHERE driver_id = NEW.driver_id
     AND violation_id <> NEW.violation_id
     AND violation_datetime >= DATE_SUB(NEW.violation_datetime, INTERVAL 365 DAY);

  IF v_prior >= 4 THEN
    SET v_rate = 0.50;      -- 5th offence or more: +50%
  ELSEIF v_prior >= 2 THEN
    SET v_rate = 0.25;      -- 3rd or 4th offence:  +25%
  END IF;

  INSERT INTO audit_log (table_name, record_id, action, driver_id, vehicle_id, new_value, acting_user)
  VALUES ('violations', NEW.violation_id, 'INSERT', NEW.driver_id, NEW.vehicle_id,
          CONCAT('case=', NEW.case_id, '; type_id=', NEW.type_id, '; at=', NEW.violation_datetime, '; location=', NEW.location),
          @current_user_id);

  INSERT INTO fines (violation_id, amount, surcharge, due_date)
  VALUES (NEW.violation_id, v_base, ROUND(v_base * v_rate, 2), DATE_ADD(CURDATE(), INTERVAL 30 DAY));
END$$

CREATE TRIGGER trg_violations_bu BEFORE UPDATE ON violations FOR EACH ROW
BEGIN
  SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Violation records are immutable. Use the appeal process instead.';
END$$

CREATE TRIGGER trg_violations_bd BEFORE DELETE ON violations FOR EACH ROW
BEGIN
  SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Violation records cannot be deleted.';
END$$

-- ===== fines: legal status transitions, audit
CREATE TRIGGER trg_fines_ai AFTER INSERT ON fines FOR EACH ROW
BEGIN
  DECLARE v_driver INT;
  DECLARE v_vehicle INT;
  SELECT driver_id, vehicle_id INTO v_driver, v_vehicle FROM violations WHERE violation_id = NEW.violation_id;
  INSERT INTO audit_log (table_name, record_id, action, driver_id, vehicle_id, new_value, acting_user)
  VALUES ('fines', NEW.fine_id, 'INSERT', v_driver, v_vehicle,
          CONCAT('status=', NEW.status, '; amount=', NEW.amount, '; surcharge=', NEW.surcharge, '; due=', NEW.due_date),
          @current_user_id);
END$$

CREATE TRIGGER trg_fines_bu BEFORE UPDATE ON fines FOR EACH ROW
BEGIN
  IF NEW.status <> OLD.status THEN
    IF NOT ( (OLD.status = 'Unpaid'  AND NEW.status IN ('Pending','Overdue','Waived'))
          OR (OLD.status = 'Overdue' AND NEW.status IN ('Pending','Waived'))
          OR (OLD.status = 'Pending' AND NEW.status IN ('Paid','Unpaid','Overdue','Waived'))
          OR (OLD.status = 'Paid'    AND NEW.status = 'Refunded') ) THEN
      SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Illegal fine status change.';
    END IF;
    IF NEW.status = 'Pending' AND NOT EXISTS (SELECT 1 FROM payments WHERE fine_id = NEW.fine_id AND status = 'Pending') THEN
      SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'A fine becomes Pending only when a payment has been submitted.';
    END IF;
    IF NEW.status = 'Paid' AND NOT EXISTS (SELECT 1 FROM payments WHERE fine_id = NEW.fine_id AND status = 'Approved') THEN
      SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'A fine can be marked Paid only after an administrator approves its payment.';
    END IF;
  END IF;
  IF OLD.status IN ('Paid','Waived','Refunded')
     AND (NEW.amount <> OLD.amount OR NEW.surcharge <> OLD.surcharge OR NEW.violation_id <> OLD.violation_id) THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'A settled fine cannot be modified.';
  END IF;
  IF NEW.status = 'Paid' AND OLD.status <> 'Paid' THEN
    SET NEW.paid_at = NOW();
  END IF;
END$$

CREATE TRIGGER trg_fines_au AFTER UPDATE ON fines FOR EACH ROW
BEGIN
  DECLARE v_driver INT;
  DECLARE v_vehicle INT;
  IF NEW.status <> OLD.status OR NEW.amount <> OLD.amount OR NEW.surcharge <> OLD.surcharge OR NEW.due_date <> OLD.due_date THEN
    SELECT driver_id, vehicle_id INTO v_driver, v_vehicle FROM violations WHERE violation_id = NEW.violation_id;
    INSERT INTO audit_log (table_name, record_id, action, driver_id, vehicle_id, old_value, new_value, acting_user)
    VALUES ('fines', NEW.fine_id, 'STATUS_CHANGE', v_driver, v_vehicle,
            CONCAT('status=', OLD.status, '; total=', (OLD.amount + OLD.surcharge), '; due=', OLD.due_date),
            CONCAT('status=', NEW.status, '; total=', (NEW.amount + NEW.surcharge), '; due=', NEW.due_date),
            @current_user_id);
  END IF;
END$$

CREATE TRIGGER trg_fines_bd BEFORE DELETE ON fines FOR EACH ROW
BEGIN
  SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Fines cannot be deleted.';
END$$

-- ===== payments: submitted as Pending, finalised only by an active administrator
CREATE TRIGGER trg_payments_bi BEFORE INSERT ON payments FOR EACH ROW
BEGIN
  DECLARE v_status VARCHAR(10);
  DECLARE v_total  DECIMAL(10,2);
  IF NEW.status IN ('Approved','Rejected') THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'A payment must start as Pending.';
  END IF;
  IF NEW.status = 'Pending' THEN
    SELECT status, total_amount INTO v_status, v_total FROM fines WHERE fine_id = NEW.fine_id;
    IF v_status NOT IN ('Unpaid','Overdue') THEN
      SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'This fine cannot be paid (already paid, awaiting approval, waived or refunded).';
    END IF;
    IF NEW.amount <> v_total THEN
      SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Payment amount must equal the fine total.';
    END IF;
    IF EXISTS (SELECT 1 FROM payments WHERE fine_id = NEW.fine_id AND status IN ('Pending','Approved')) THEN
      SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'A payment already exists for this fine.';
    END IF;
  END IF;
END$$

CREATE TRIGGER trg_payments_ai AFTER INSERT ON payments FOR EACH ROW
BEGIN
  DECLARE v_driver INT;
  DECLARE v_vehicle INT;
  SELECT v.driver_id, v.vehicle_id INTO v_driver, v_vehicle
    FROM fines f JOIN violations v ON v.violation_id = f.violation_id WHERE f.fine_id = NEW.fine_id;
  INSERT INTO audit_log (table_name, record_id, action, driver_id, vehicle_id, new_value, acting_user)
  VALUES ('payments', NEW.payment_id, 'INSERT', v_driver, v_vehicle,
          CONCAT('fine_id=', NEW.fine_id, '; ', NEW.status, '; ', NEW.method, '; ref=', NEW.reference_no, '; amount=', NEW.amount),
          @current_user_id);
END$$

CREATE TRIGGER trg_payments_bu BEFORE UPDATE ON payments FOR EACH ROW
BEGIN
  IF OLD.status <> 'Pending' THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'A reviewed payment is final and cannot be changed.';
  END IF;
  IF NEW.status NOT IN ('Approved','Rejected') THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'A pending payment can only be approved or rejected.';
  END IF;
  IF NEW.fine_id <> OLD.fine_id OR NEW.amount <> OLD.amount OR NEW.reference_no <> OLD.reference_no
     OR NEW.method <> OLD.method OR NEW.user_id <> OLD.user_id THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Payment details cannot be changed.';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM users WHERE user_id = @current_user_id AND role = 'admin' AND approval_status = 'Approved') THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Only an active administrator can review payments.';
  END IF;
END$$

CREATE TRIGGER trg_payments_au AFTER UPDATE ON payments FOR EACH ROW
BEGIN
  DECLARE v_driver INT;
  DECLARE v_vehicle INT;
  IF NEW.status <> OLD.status THEN
    SELECT v.driver_id, v.vehicle_id INTO v_driver, v_vehicle
      FROM fines f JOIN violations v ON v.violation_id = f.violation_id WHERE f.fine_id = NEW.fine_id;
    INSERT INTO audit_log (table_name, record_id, action, driver_id, vehicle_id, old_value, new_value, acting_user)
    VALUES ('payments', NEW.payment_id, 'STATUS_CHANGE', v_driver, v_vehicle,
            CONCAT('status=', OLD.status), CONCAT('status=', NEW.status, '; ref=', NEW.reference_no, '; note=', COALESCE(NEW.review_note,'')),
            @current_user_id);
  END IF;
END$$

CREATE TRIGGER trg_payments_bd BEFORE DELETE ON payments FOR EACH ROW
BEGIN
  SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Payment records cannot be deleted.';
END$$

-- ===== appeals
CREATE TRIGGER trg_appeals_bi BEFORE INSERT ON appeals FOR EACH ROW
BEGIN
  DECLARE v_driver INT;
  DECLARE v_fine_status VARCHAR(10);
  SELECT v.driver_id, f.status INTO v_driver, v_fine_status
    FROM violations v JOIN fines f ON f.violation_id = v.violation_id
   WHERE v.violation_id = NEW.violation_id;
  IF v_driver IS NULL OR v_driver <> NEW.driver_id THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'You can only appeal your own violations.';
  END IF;
  IF v_fine_status IN ('Waived','Refunded') THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'This violation has already been cleared.';
  END IF;
  IF EXISTS (SELECT 1 FROM appeals WHERE violation_id = NEW.violation_id) THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'An appeal already exists for this violation.';
  END IF;
  SET NEW.status = 'Pending';
END$$

CREATE TRIGGER trg_appeals_ai AFTER INSERT ON appeals FOR EACH ROW
BEGIN
  DECLARE v_vehicle INT;
  SELECT vehicle_id INTO v_vehicle FROM violations WHERE violation_id = NEW.violation_id;
  INSERT INTO audit_log (table_name, record_id, action, driver_id, vehicle_id, new_value, acting_user)
  VALUES ('appeals', NEW.appeal_id, 'INSERT', NEW.driver_id, v_vehicle,
          CONCAT('violation_id=', NEW.violation_id, '; status=Pending'), @current_user_id);
END$$

CREATE TRIGGER trg_appeals_bu BEFORE UPDATE ON appeals FOR EACH ROW
BEGIN
  IF OLD.status <> 'Pending' THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'A resolved appeal cannot be changed.';
  END IF;
END$$

CREATE TRIGGER trg_appeals_au AFTER UPDATE ON appeals FOR EACH ROW

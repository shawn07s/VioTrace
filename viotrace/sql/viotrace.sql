    VALUES ('appeals', NEW.appeal_id, 'STATUS_CHANGE', NEW.driver_id, v_vehicle,
            CONCAT('status=', OLD.status), CONCAT('status=', NEW.status, '; remarks=', COALESCE(NEW.admin_remarks,'')),
            @current_user_id);
  END IF;
END$$

CREATE TRIGGER trg_appeals_bd BEFORE DELETE ON appeals FOR EACH ROW
BEGIN

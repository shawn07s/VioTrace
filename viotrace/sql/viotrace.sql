-- Flags unpaid fines past their due date (fines with a payment awaiting approval are left alone).
CREATE PROCEDURE sp_mark_overdue()
BEGIN
  UPDATE fines SET status = 'Overdue' WHERE status = 'Unpaid' AND due_date < CURDATE();
END$$

-- Admin approval of a submitted payment: one atomic transaction with row locks.
-- Approved -> payment Approved, fine Paid.  Rejected -> payment Rejected, fine back to Unpaid/Overdue.
CREATE PROCEDURE sp_review_payment(IN p_payment_id INT, IN p_admin_id INT,
                                   IN p_decision VARCHAR(10), IN p_note VARCHAR(255))
BEGIN
  DECLARE v_fine   INT;
  DECLARE v_pstatus VARCHAR(10);
  DECLARE v_fstatus VARCHAR(10);
  DECLARE v_due    DATE;
  DECLARE EXIT HANDLER FOR SQLEXCEPTION
  BEGIN
    ROLLBACK;
    RESIGNAL;
  END;

  IF p_decision NOT IN ('Approved','Rejected') THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Decision must be Approved or Rejected.';
  END IF;

  START TRANSACTION;
  SELECT fine_id, status INTO v_fine, v_pstatus FROM payments WHERE payment_id = p_payment_id FOR UPDATE;
  IF v_pstatus IS NULL OR v_pstatus <> 'Pending' THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Payment not found or already reviewed.';
  END IF;
  SELECT status, due_date INTO v_fstatus, v_due FROM fines WHERE fine_id = v_fine FOR UPDATE;
  IF v_fstatus <> 'Pending' THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'The fine is no longer awaiting payment approval.';
  END IF;

  UPDATE payments SET status = p_decision, reviewed_by = p_admin_id, reviewed_at = NOW(), review_note = p_note
   WHERE payment_id = p_payment_id;

  IF p_decision = 'Approved' THEN
    UPDATE fines SET status = 'Paid' WHERE fine_id = v_fine;
  ELSE
    UPDATE fines SET status = IF(v_due < CURDATE(), 'Overdue', 'Unpaid') WHERE fine_id = v_fine;
  END IF;
  COMMIT;
END$$

-- Appeal resolution as ONE atomic transaction with row locks.
-- Approved: unpaid/overdue fine -> Waived; fine with a pending payment -> payment Rejected + Waived;
--           paid fine -> Refunded.
CREATE PROCEDURE sp_resolve_appeal(IN p_appeal_id INT, IN p_admin_id INT,
                                   IN p_outcome VARCHAR(10), IN p_remarks VARCHAR(500))
BEGIN
  DECLARE v_violation   INT;
  DECLARE v_status      VARCHAR(10);
  DECLARE v_fine        INT;
  DECLARE v_fine_status VARCHAR(10);
  DECLARE EXIT HANDLER FOR SQLEXCEPTION
  BEGIN
    ROLLBACK;
    RESIGNAL;
  END;

  IF p_outcome NOT IN ('Approved','Rejected') THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Outcome must be Approved or Rejected.';
  END IF;

  START TRANSACTION;
  SELECT violation_id, status INTO v_violation, v_status
    FROM appeals WHERE appeal_id = p_appeal_id FOR UPDATE;
  IF v_status IS NULL OR v_status <> 'Pending' THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Appeal not found or already resolved.';
  END IF;
  SELECT fine_id, status INTO v_fine, v_fine_status FROM fines WHERE violation_id = v_violation FOR UPDATE;

  IF p_outcome = 'Approved' THEN
    IF v_fine_status IN ('Unpaid','Overdue') THEN
      UPDATE fines SET status = 'Waived' WHERE fine_id = v_fine;
    ELSEIF v_fine_status = 'Pending' THEN
      UPDATE payments SET status = 'Rejected', reviewed_by = p_admin_id, reviewed_at = NOW(),
             review_note = 'Fine waived after an approved appeal'
       WHERE fine_id = v_fine AND status = 'Pending';
      UPDATE fines SET status = 'Waived' WHERE fine_id = v_fine;
    ELSEIF v_fine_status = 'Paid' THEN
      UPDATE fines SET status = 'Refunded' WHERE fine_id = v_fine;
    END IF;
  END IF;

  UPDATE appeals SET status = p_outcome, admin_id = p_admin_id,
         admin_remarks = p_remarks, resolved_at = NOW()
   WHERE appeal_id = p_appeal_id;
  COMMIT;
END$$

